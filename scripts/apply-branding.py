#!/usr/bin/env python3
"""Synchronize display names from config/branding.json without changing app IDs.

Run with --apply to write changes or --check to fail when generated files drift.
The default is a read-only preview. Android reads the manifest during its build.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import shlex
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "Generated by scripts/apply-branding.py from config/branding.json."


def read_branding(root: Path) -> dict[str, str]:
    data = json.loads((root / "config/branding.json").read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema") != 1:
        raise ValueError("config/branding.json must have schema=1")
    for key in ("displayName", "desktopName"):
        value = data.get(key)
        # These names enter Android resources, shell metadata and desktop entries.
        # Keep their grammar deliberately small; never interpolate arbitrary code.
        if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9 .-]{0,63}", value) or value != value.strip():
            raise ValueError(f"{key} must be 1–64 letters, digits, spaces, dots or hyphens, starting with a letter")
    return data


def replace_title(source: str, title: str) -> str:
    result, count = re.subn(r"<title>[^<]*</title>", f"<title>{html.escape(title)}</title>", source)
    if count != 1:
        raise ValueError("expected exactly one HTML title")
    return result


def planned_files(root: Path) -> dict[str, str]:
    branding = read_branding(root)
    name, desktop_name = branding["displayName"], branding["desktopName"]
    desktop = "desktop/apps/desktop-tauri/"
    config_path = desktop + "src-tauri/tauri.conf.json"
    config = json.loads((root / config_path).read_text(encoding="utf-8"))
    config["productName"] = desktop_name
    windows = config["app"]["windows"]
    if len(windows) != 1:
        raise ValueError("review branding targets before adding Tauri windows")
    windows[0]["title"] = desktop_name
    return {
        desktop + "src/config/branding.ts": f"// {GENERATED}\nexport const APP_NAME = {json.dumps(name)};\n",
        desktop + "src-tauri/src/branding.rs": f"// {GENERATED}\npub(crate) const APP_NAME: &str = {json.dumps(name)};\n",
        config_path: json.dumps(config, indent=2, ensure_ascii=False) + "\n",
        desktop + "index.html": replace_title((root / (desktop + "index.html")).read_text(encoding="utf-8"), desktop_name),
        desktop + "public/x11-warning.html": replace_title((root / (desktop + "public/x11-warning.html")).read_text(encoding="utf-8"), name + " - X11 Legacy Notice"),
        "config/branding.sh": f"# {GENERATED}\nWBEAM_PRODUCT_NAME={shlex.quote(name)}\nWBEAM_DESKTOP_NAME={shlex.quote(desktop_name)}\n",
        "config/waybeam.desktop": (
            f"# {GENERATED}\n[Desktop Entry]\nType=Application\nVersion=1.0\n"
            f"Name={desktop_name}\nComment={name} desktop control and host service manager\n"
            "Exec=/usr/local/bin/waybeam-desktop\nIcon=wbeam\nTerminal=false\n"
            "Categories=Utility;Network;\nStartupNotify=true\n"
        ),
    }


def synchronize(root: Path, apply: bool = False) -> list[str]:
    # Validate and calculate all outputs before writing any file.
    planned = planned_files(root)
    changed = []
    for relative, content in planned.items():
        path = root / relative
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(relative)
        if apply:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="update the allowlisted display-name files")
    mode.add_argument("--check", action="store_true", help="exit 1 if generated branding is out of date")
    args = parser.parse_args()
    try:
        changed = synchronize(ROOT, args.apply)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.exit(2, f"[branding] {exc}\n")
    for path in changed:
        print(f"[branding] {'updated' if args.apply else 'would update'} {path}")
    if not changed:
        print("[branding] display names are consistent")
    elif not args.apply:
        print("[branding] run python3 scripts/apply-branding.py --apply to synchronize")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
